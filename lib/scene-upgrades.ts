export function upgradeCrates(crates: CrateDef[]): CrateDef[] {
  return crates.map((c) => {
    const now = SCENE_BY_ID[c.id];
    if (!now) return c;
    const unedited = (was?: string[]) => !!was && was.length === c.artists.length && was.every((a) => c.artists.some((x) => norm(x) === norm(a)));
    return unedited(BEFORE[c.id]) || unedited(BEFORE_V2[c.id]) ? { ...c, artists: [...now.artists], years: now.years } : c;
  });
}
